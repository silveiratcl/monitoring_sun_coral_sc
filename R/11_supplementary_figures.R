      y = rai_w,
      colour = localidade
    ),
    size = 2
  ) +
  
  geom_errorbar(
    data = temporal_summary,
    aes(
      x = monitoring_cycle,
      ymin = raiw_lower,
      ymax = raiw_upper
    ),
    width = 0.08,
    linewidth = 0.9,
    colour = "black"
  ) +
  
  geom_line(
    data = temporal_summary,
    aes(
      x = monitoring_cycle,
      y = rai_w,
      group = 1
    ),
    linewidth = 1.2,
    colour = "black"
  ) +
  
  geom_point(
    data = temporal_summary,
    aes(
      x = monitoring_cycle,
      y = rai_w
    ),
    size = 3,
    colour = "black"
  ) +
  
  scale_x_discrete(
    drop = FALSE
  ) +
  
  labs(
    x = "Monitoring cycle",
    y = "RAI-W",
    colour = "Locality"
  ) +
  
  theme_bw(
    base_size = 13
  ) +
  
  theme(
    panel.grid.minor =
      element_blank(),
    
    legend.position =
      "right"
  )


################################################################################
# S1.6. Combine Figure S1
################################################################################

figure_s1 <- (
  plot_s1a +
    plot_s1b
) +
  plot_layout(
    ncol = 2,
    guides = "collect"
  ) +
  plot_annotation(
    tag_levels = "A"
  ) &
  
  theme(
    legend.position =
      "right",
    
    legend.title =
      element_text(
        face = "bold"
      ),
    
    plot.tag =
      element_text(
        face = "bold",
        size = 14
      )
  )


figure_s1


################################################################################
# S1.7. Export Figure S1
################################################################################

ggsave(
  filename =
    "figs/Figure_S1_temporal_effort_standardised.png",
  
  plot =
    figure_s1,
  
  width = 14,
  height = 7,
  units = "in",
  dpi = 300
)


